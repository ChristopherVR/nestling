/// Device-local language; user-entered names and notes are kept as entered.
abstract final class AppLanguage {
  static String _code = 'en';
  static String get code => _code;
  static void use(String code) {
    _code = code == 'af' ? 'af' : 'en';
    Intl.defaultLocale = _code;
  }
}

String tr(String text, {String? language}) {
  if (text.isEmpty) return text;
  text = _translate(text, habitWording, _habitPatterns);
  if ((language ?? AppLanguage.code) != 'af') return text;
  return _translate(text, afrikaans, _patterns);
}

String _translate(
  String text,
  Map<String, String> table,
  List<_TranslationPattern> patterns,
) {
  final exact = table[text];
  if (exact != null) return exact;
  for (final entry in patterns) {
    final match = entry.pattern.firstMatch(text);
    if (match == null) continue;
    var translated = entry.translation;
    for (var i = 0; i < entry.parameters.length; i++) {
      translated = translated.replaceAll(
        '{${entry.parameters[i]}}',
        match.group(i + 1)!,
      );
    }
    return translated;
  }
  for (final separator in ['\n', ' · ', ', ']) {
    if (text.contains(separator)) {
      return text
          .split(separator)
          .map((part) => _translate(part, table, patterns))
          .join(separator);
    }
  }
  return text;
}

List<_TranslationPattern> _patternsOf(Map<String, String> table) => [
  for (final entry in table.entries)
    if (entry.key.contains('{')) _TranslationPattern(entry.key, entry.value),
]..sort((a, b) => b.specificity.compareTo(a.specificity));

final _patterns = _patternsOf(afrikaans);
final _habitPatterns = _patternsOf(habitWording);

class _TranslationPattern {
  late final RegExp pattern;
  final String translation;
  final List<String> parameters = [];
  final int specificity;
  _TranslationPattern(String source, this.translation)
    : specificity = source.replaceAll(RegExp(r'\{[^}]+\}'), '').length {
    final placeholder = RegExp(r'\{([a-zA-Z]+)\}');
    var offset = 0;
    var expression = '^';
    for (final match in placeholder.allMatches(source)) {
      expression += RegExp.escape(source.substring(offset, match.start));
      expression += '(.*?)';
      parameters.add(match.group(1)!);
      offset = match.end;
    }
    expression += '${RegExp.escape(source.substring(offset))}\$';
    pattern = RegExp(expression, dotAll: true);
  }
}

/// Const-friendly localized text keeps existing screens and dialog styles.
class LText extends StatelessWidget {
  const LText(
    this.data, {
    super.key,
    this.style,
    this.textAlign,
    this.overflow,
    this.maxLines,
    this.softWrap,
  }) : localize = true;
  const LText.raw(
    this.data, {
    super.key,
    this.style,
    this.textAlign,
    this.overflow,
    this.maxLines,
    this.softWrap,
  }) : localize = false;
  final bool localize;
  final String data;
  final TextStyle? style;
  final TextAlign? textAlign;
  final TextOverflow? overflow;
  final int? maxLines;
  final bool? softWrap;
  @override
  Widget build(BuildContext context) => Text(
    localize
        ? tr(data, language: Localizations.localeOf(context).languageCode)
        : data,
    style: style,
    textAlign: textAlign,
    overflow: overflow,
    maxLines: maxLines,
    softWrap: softWrap,
  );
}

class LIconButton extends StatelessWidget {
  const LIconButton({
    super.key,
    required this.icon,
    required this.onPressed,
    this.tooltip,
  });
  final Widget icon;
  final VoidCallback? onPressed;
  final String? tooltip;
  @override
  Widget build(BuildContext context) => IconButton(
    icon: icon,
    onPressed: onPressed,
    tooltip: tooltip == null
        ? null
        : tr(tooltip!, language: Localizations.localeOf(context).languageCode),
  );
}

